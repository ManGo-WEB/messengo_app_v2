// Типы подключений V2 → иконки.
const CHANNEL_BRAND: Record<ChannelType, string> = {
  VK: "vk",
  TELEGRAM_BOT: "telegram",
  TELEGRAM_PERSONAL: "telegram",
  WHATSAPP: "whatsapp",
  MAX: "max",
  FACEBOOK: "facebook",
  INSTAGRAM: "instagram",
  TESTING: "logo",
};

export type ChannelIconBrand = keyof typeof OFFICIAL_LOGOS | TileBrandId;

export default function ChannelIcon({
  id,
  size = 32,
  mono = false,
  className = "",
  style,
}: {
  /** Тип подключения V2 (VK, TELEGRAM_BOT, …) или бренд прототипа (vk, telegram, …). */
  id: string;
  size?: number;
  mono?: boolean;
  className?: string;
  style?: CSSProperties;
}) {
  const gradientId = useId().replace(/:/g, "");
  const brandId: ChannelIconBrand =
    id in OFFICIAL_LOGOS || id in TILE_BRANDS
      ? (id as ChannelIconBrand)
      : (CHANNEL_BRAND[id as ChannelType] ?? "logo"); // неизвестный тип — нейтральная плитка

  const official = OFFICIAL_LOGOS[brandId];
  if (official) {
    return (
      <span className={`ch-icon ${className}`} style={{ width: size, height: size, ...style }} aria-hidden="true">
        {official.asset ? (
          // Официальный ассет брендбука MAX — SVG с маской и многоколольным
          // градиентом; next/image для декоративной иконки не применяется
          // eslint-disable-next-line @next/next/no-img-element
          <img
            src={official.asset}
            width={size}
            height={size}
            alt=""
            style={mono ? { filter: "grayscale(1)" } : undefined}
          />
        ) : (
          <svg width={size} height={size} viewBox="0 0 24 24" role="img">
            {official.gradient && (
              <defs>
                {official.gradient === "telegram" && (
                  <linearGradient id={`chicon-${gradientId}`} x1="0" y1="0" x2="0" y2="1">
                    <stop offset="0" stopColor="#2AABEE" />
                    <stop offset="1" stopColor="#229ED9" />
                  </linearGradient>
                )}
                {official.gradient === "instagram" && (
                  <radialGradient id={`chicon-${gradientId}`} cx="0.3" cy="1.07" r="1.4">
                    <stop offset="0" stopColor="#fdf497" />
                    <stop offset="0.05" stopColor="#fdf497" />
                    <stop offset="0.45" stopColor="#fd5949" />
                    <stop offset="0.6" stopColor="#d6249f" />
                    <stop offset="0.9" stopColor="#285AEB" />
                  </radialGradient>
                )}
              </defs>
            )}
            <path d={official.d} fill={mono ? MONO_COLOR : official.gradient ? `url(#chicon-${gradientId})` : official.color} />
          </svg>
        )}
      </span>
    );
  }

  // Плитка с глифом — каналы без официального лого и неизвестные типы
  const tile = TILE_BRANDS[brandId as TileBrandId] ?? TILE_BRANDS.logo;
  return (
    <span
      className={`ch-icon ${className}`}
      style={{
        width: size,
        height: size,
        background: mono ? "#e9f0fd" : tile.bg,
        color: mono ? MONO_COLOR : "#ffffff",
        fontSize: size,
        ...style,
      }}
      aria-hidden="true"
    >
      <svg width={Math.round(size * 0.58)} height={Math.round(size * 0.58)} viewBox="0 0 24 24">
        {GLYPHS[tile.glyph]}
      </svg>
    </span>
  );
}
